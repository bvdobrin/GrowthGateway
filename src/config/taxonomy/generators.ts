import type { Asset, AssetFile, AssetFormat, CategoryDefinition, MetadataValue } from '@/types';

export interface GeneratorParam {
  key: string;
  /** Free text, such as a prompt. Defaults to a select. */
  kind?: 'select' | 'text';
  options?: string[];
  required?: boolean;
}

export interface GeneratorOutput {
  title: string;
  description: string;
  format: AssetFormat;
  files: Omit<AssetFile, 'id'>[];
  categoryMetadata?: Record<string, MetadataValue>;
  /** When set, the draft is this category rather than the source asset's category. */
  categoryId?: string;
  locale?: string;
}

export interface GeneratorDefinition {
  id: string;
  icon: string;
  /** Global generators are offered for every category they apply to. */
  global?: boolean;
  params?: GeneratorParam[];
  appliesTo?: (asset: Asset, category: CategoryDefinition) => boolean;
  run: (asset: Asset, category: CategoryDefinition, params: Record<string, string>) => GeneratorOutput;
}

const VISUAL: AssetFormat[] = ['image', 'design'];
const TEXTUAL: AssetFormat[] = ['text', 'html'];

const sourceText = (asset: Asset) =>
  asset.files
    .map((f) => f.text ?? '')
    .join('\n')
    .replace(/<[^>]+>/g, ' ')
    .replace(/[#*_>`-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

const sentences = (asset: Asset, count: number) => {
  const text = `${asset.description} ${sourceText(asset)}`;
  return (text.match(/[^.!?。]+[.!?。]/g) ?? [text]).map((s) => s.trim()).filter(Boolean).slice(0, count);
};

const textFile = (name: string, text: string, role: AssetFile['role'] = 'primary', mime = 'text/markdown'): Omit<AssetFile, 'id'> => ({
  role,
  name,
  mime,
  sizeBytes: new Blob([text]).size,
  text,
});

const AI_NOTE = '\n\n---\n*Generated by GrowthGateway AI (mock). Review before use.*\n';

const textOutput = (asset: Asset, suffix: string, body: string, fileSuffix: string): GeneratorOutput => ({
  title: `${asset.title}: ${suffix}`,
  description: `${suffix} generated from "${asset.title}".`,
  format: 'text',
  files: [textFile(`${slugify(asset.title)}-${fileSuffix}.md`, `${body}${AI_NOTE}`)],
});

const visualOutput = (
  asset: Asset,
  category: CategoryDefinition,
  suffix: string,
  width: number,
  height: number,
  extra: { subtitle?: string; transparent?: boolean; metadata?: Record<string, MetadataValue> } = {},
): GeneratorOutput => {
  const svg = svgArtwork({
    title: asset.title,
    subtitle: extra.subtitle ?? suffix,
    format: 'image',
    colorToken: category.colorToken,
    width,
    height,
    transparent: extra.transparent,
  });
  return {
    title: `${asset.title} (${suffix})`,
    description: `${suffix} generated from "${asset.title}".`,
    format: 'image',
    files: [{ role: 'primary', name: `${slugify(asset.title)}-${slugify(suffix)}.svg`, mime: 'image/svg+xml', sizeBytes: svg.length, width, height, text: svg }],
    categoryMetadata: extra.metadata,
  };
};

/** Keeps the parent's files and adds generated companions (captions, transcripts, summaries). */
const augment = (asset: Asset, suffix: string, added: Omit<AssetFile, 'id'>[], metadata?: Record<string, MetadataValue>): GeneratorOutput => ({
  title: `${asset.title} (${suffix})`,
  description: `${asset.description} ${suffix} added by GrowthGateway AI.`,
  format: asset.format,
  files: [...asset.files.map(({ id: _id, ...file }) => file), ...added],
  categoryMetadata: metadata,
});

