export const GENERATORS_BY_ID: Record<string, GeneratorDefinition> = Object.fromEntries(GENERATORS.map((g) => [g.id, g]));

/** Category generators plus global generators that apply to this asset. */
export function generatorsFor(asset: Asset, category: CategoryDefinition): GeneratorDefinition[] {
  const own = category.generatorIds.map((id) => GENERATORS_BY_ID[id]).filter((g): g is GeneratorDefinition => !!g);
  const global = GENERATORS.filter((g) => g.global && !category.generatorIds.includes(g.id));
  return [...own, ...global].filter((g) => !g.appliesTo || g.appliesTo(asset, category));
}
