const toAsset = (spec: Spec): Asset => {
  const id = `ast-${String(spec.id).padStart(3, '0')}`;
  const createdAt = `${spec.created}T09:00:00.000Z`;
  const primaryName = spec.files[0]?.name ?? spec.title;
  return {
    id,
    title: spec.title,
    description: spec.description,
    category: spec.category,
    format: spec.format,
    files: spec.files.map((file, index) => ({
      ...file,
      id: `${id}-f${index + 1}`,
      mime: file.mime ?? mimeForName(file.name),
      sizeBytes: Math.round(file.sizeBytes),
    })),
    categoryMetadata: spec.meta ?? {},
    region: spec.region,
    locale: spec.locale,
    businessUnit: spec.bu,
    campaign: spec.campaign,
    tags: spec.tags,
    sourceSystem: spec.source,
    migrationStatus: spec.linked ? 'linked' : 'migrated',
    sourcePath: spec.source === 'gg-native' ? undefined : legacyPath(spec.source, primaryName),
    classification: spec.classification,
    accessGroups: spec.groups,
    status: spec.status,
    rightsExpiry: spec.rightsExpiry,
    ownerId: spec.owner,
    approval: spec.approval,
    submittedAt: spec.status === 'pending_approval' ? createdAt : undefined,
    submittedBy: spec.status === 'pending_approval' ? spec.owner : undefined,
    createdAt,
    updatedAt: createdAt,
  };
};

export const createSeedAssets = (): Asset[] => SPECS.map(toAsset);
