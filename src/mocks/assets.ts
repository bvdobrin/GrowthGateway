interface Spec {
  id: number;
  title: string;
  description: string;
  category: string;
  format: AssetFormat;
  region: Region;
  locale: string;
  bu: string;
  campaign?: string;
  tags: string[];
  source: string;
  linked?: boolean;
  classification: Classification;
  groups: string[];
  status: AssetStatus;
  owner: string;
  created: string;
  rightsExpiry?: string;
  meta?: Record<string, MetadataValue>;
  files: FileSpec[];
  approval?: ApprovalDecision;
}

const primary = (name: string, sizeBytes: number, extra: Partial<FileSpec> = {}): FileSpec => ({
  role: 'primary',
  name,
  sizeBytes,
  ...extra,
});
const textFile = (role: AssetFile['role'], name: string, text: string): FileSpec => ({
  role,
  name,
  sizeBytes: new Blob([text]).size,
  text,
});
const attachment = (name: string, sizeBytes: number): FileSpec => ({ role: 'attachment', name, sizeBytes });

