/**
 * Builds the design tokens in `tokens/` (DTCG JSON) into:
 *   src/styles/generated/tokens.css        custom properties: light on :root, dark on [data-theme="dark"]
 *   src/styles/generated/custom-media.css  @custom-media rules for the breakpoint tokens
 *   src/styles/generated/tokens.ts         resolved values for the few places JS needs them
 *
 * Run with `npm run tokens:build` (also runs before dev, build and test).
 */
import StyleDictionary from 'style-dictionary';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';

const OUT = 'src/styles/generated/';
const TMP = `${OUT}.tmp/`;
const transforms = ['attribute/cti', 'name/kebab'];
const valueOf = (token) => token.$value ?? token.value;
const isSemantic = (theme) => (token) => token.filePath.includes(`semantic/${theme}`);

StyleDictionary.registerFormat({
  name: 'gg/custom-media',
  format: ({ dictionary }) => {
    const lines = dictionary.allTokens
      .filter((token) => token.path[0] === 'bp')
      .flatMap((token) => [
        `@custom-media --${token.name} (width >= ${valueOf(token)});`,
        `@custom-media --${token.name}-below (width < ${valueOf(token)});`,
      ]);
    lines.push('@custom-media --motion-ok (prefers-reduced-motion: no-preference);');
    return `/* Generated by Style Dictionary. Do not edit. */\n${lines.join('\n')}\n`;
  },
});

StyleDictionary.registerFormat({
  name: 'gg/ts',
  format: ({ dictionary, options }) => {
    const entries = dictionary.allTokens
      .map((token) => `  ${JSON.stringify(token.name)}: ${JSON.stringify(String(valueOf(token)))},`)
      .join('\n');
    return `export const ${options.exportName} = {\n${entries}\n} as const;\n`;
  },
});

const light = new StyleDictionary({
  source: ['tokens/primitive/**/*.json', 'tokens/semantic/light.json'],
  log: { verbosity: 'silent' },
  platforms: {
    css: {
      transforms,
      buildPath: TMP,
      files: [
        {
          destination: 'light.css',
          format: 'css/variables',
          options: { selector: ':root', outputReferences: true },
        },
        { destination: 'custom-media.css', format: 'gg/custom-media' },
      ],
    },
    ts: {
      transforms,
      buildPath: TMP,
      files: [{ destination: 'light.ts', format: 'gg/ts', options: { exportName: 'tokens' } }],
    },
  },
});

const dark = new StyleDictionary({
  source: ['tokens/primitive/**/*.json', 'tokens/semantic/dark.json'],
  log: { verbosity: 'silent' },
  platforms: {
    css: {
      transforms,
      buildPath: TMP,
      files: [
        {
          destination: 'dark.css',
          format: 'css/variables',
          filter: isSemantic('dark'),
          options: { selector: '[data-theme="dark"]', outputReferences: false },
        },
      ],
    },
    ts: {
      transforms,
      buildPath: TMP,
      files: [
        {
          destination: 'dark.ts',
          format: 'gg/ts',
          filter: isSemantic('dark'),
          options: { exportName: 'darkTokens' },
        },
      ],
    },
  },
});

await mkdir(TMP, { recursive: true });
await light.buildAllPlatforms();
await dark.buildAllPlatforms();

const read = (file) => readFile(`${TMP}${file}`, 'utf8');
const header = '/* Generated by Style Dictionary from tokens/. Do not edit. */\n';

await writeFile(`${OUT}tokens.css`, `${header}${await read('light.css')}\n${await read('dark.css')}`);
await writeFile(`${OUT}custom-media.css`, await read('custom-media.css'));
await writeFile(
  `${OUT}tokens.ts`,
  `${header}${await read('light.ts')}\n${await read('dark.ts')}\nexport type TokenName = keyof typeof tokens;\n\nexport const cssVar = (name: TokenName): string => \`var(--\${name})\`;\n`,
);
await rm(TMP, { recursive: true, force: true });

console.log('tokens: built tokens.css, custom-media.css, tokens.ts');
